// Package engine 是一个带二级索引与覆盖扫描的嵌入式记录存储。
//
// 现有主表通路（按主键读写、主键顺序遍历）保持不变；在此之上提供：
//
//   - 多字段二级索引（唯一 / 非唯一、单列 / 复合、带覆盖附加列），
//     记录的插入、更新、删除自动维护全部相关索引；
//   - 事务/批次提交（快照隔离，first-committer-wins），原子可见、可回滚；
//   - 无锁快照读与串行化提交，支持索引维护与查询并发，go test -race 安全；
//   - 覆盖扫描：所需字段全部能从索引项取用时不回表，结果中可观测回表次数；
//   - 保序字节编码：范围查询、前缀查询边界语义确定；
//   - 从主表全量重建索引，并可检测/报告索引与主表的偏差。
//
// 典型用法见 README 与各测试。
